organization TEXT NOT NULL, subject TEXT NOT NULL, digest TEXT NOT NULL, body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS l18_outbox(event TEXT PRIMARY KEY, kind TEXT NOT NULL, body TEXT NOT NULL);
