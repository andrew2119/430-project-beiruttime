CREATE TABLE IF NOT EXISTS l18_results(subject TEXT PRIMARY KEY, revision INTEGER NOT NULL, body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS l18_history(subject TEXT NOT NULL, revision INTEGER NOT NULL,
body TEXT NOT NULL, PRIMARY KEY(subject,revision));
